"""Builds legal-content.mjs for the compliance edge worker from the drafted Markdown.

Usage: python3 build.py [EFFECTIVE_DATE]   e.g. python3 build.py "November 3, 2026"
Without a date the "[EFFECTIVE DATE — set on publish]" placeholder is kept (fine for testing, not for deploy).
"""
import html, json, os, sys
import markdown

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATE = sys.argv[1] if len(sys.argv) > 1 else None

SITES = {
    "bdh": dict(dir="bdhconsultants.com", name="BDH Consultants", slash=True,
                consent=True, accent="#1f3b33"),
    "env": dict(dir="environmentlending.com", name="enviRŌNment", slash=False,
                consent=False, accent="#0f5c63"),
}
DOCS = [("privacy", "privacy-policy.md", "Privacy Policy"),
        ("terms", "terms-of-use.md", "Terms of Use"),
        ("accessibility", "accessibility-statement.md", "Accessibility Statement")]

def page(site, key, title, md):
    s = SITES[site]
    if DATE:
        md = md.replace("[EFFECTIVE DATE — set on publish]", DATE)
    body = markdown.markdown(md, extensions=["tables"])
    sl = "/" if s["slash"] else ""
    links = " ".join(f'<a href="/{k}{sl}"{" aria-current=\"page\"" if k == key else ""}>{t}</a>' for k, _, t in DOCS)
    if s["consent"]:
        links += ' <a href="#privacy-choices" data-consent-open>Your Privacy Choices</a>'
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)} | {html.escape(s['name'])}</title><meta name="robots" content="index,follow">
<style>
:root{{--accent:{s['accent']}}}*{{box-sizing:border-box}}body{{margin:0;font:17px/1.7 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;color:#1a1a1a;background:#fff}}
.skip{{position:absolute;left:-9999px}}.skip:focus{{left:16px;top:16px;background:#fff;padding:8px 12px;border:2px solid #111;z-index:10}}
header,main,footer{{max-width:820px;margin:0 auto;padding:0 20px}}header{{padding-top:28px;padding-bottom:12px;border-bottom:1px solid #ddd}}
header a{{font-weight:700;font-size:20px;color:#111;text-decoration:none}}main{{padding-top:24px;padding-bottom:48px}}
h1{{font-size:38px;line-height:1.2;margin:.4em 0}}h2{{font-size:23px;margin:1.8em 0 .4em}}h3{{font-size:19px}}
a{{color:var(--accent);text-decoration:underline}}table{{border-collapse:collapse;width:100%;font-size:15px;margin:16px 0;display:block;overflow-x:auto}}
th,td{{border:1px solid #ccc;padding:8px;text-align:left;vertical-align:top}}th{{background:#f2f2f2}}
footer{{border-top:1px solid #ddd;padding-top:16px;padding-bottom:40px;font-size:15px}}footer nav{{display:flex;flex-wrap:wrap;gap:8px 20px}}
:focus-visible{{outline:3px solid #0b57d0;outline-offset:2px}}
</style>{'<script>window.CONSENT_CONFIG={"policyUrl":"/privacy/"};</script><script src="/__compliance/consent.js" defer></script>' if s['consent'] else ''}
</head><body><a class="skip" href="#main">Skip to content</a>
<header><a href="/">{html.escape(s['name'])}</a></header>
<main id="main">{body}<p><a href="/">Back to the {html.escape(s['name'])} home page</a></p></main>
<footer><nav aria-label="Legal">{links}</nav></footer>
</body></html>"""

out = {}
for site, s in SITES.items():
    for key, fn, title in DOCS:
        md = open(os.path.join(ROOT, s["dir"], fn), encoding="utf-8").read()
        out[f"{site}:{key}"] = page(site, key, title, md)
consent = open(os.path.join(ROOT, "shared", "consent.js"), encoding="utf-8").read()
mod = "// Generated by build.py. Do not edit by hand.\n"
mod += "export const LEGAL = " + json.dumps(out, ensure_ascii=False) + ";\n"
mod += "export const CONSENT_JS = " + json.dumps(consent, ensure_ascii=False) + ";\n"
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "legal-content.mjs"), "w", encoding="utf-8").write(mod)
print("built", len(mod), "bytes", "date:", DATE or "(placeholder)")
